/**
 * Registry freshness check. Runs monthly in CI (registry-check.yml) and
 * prints a markdown report:
 *
 *  1. Every hfId in src/engine/registry.ts is verified against the
 *     Hugging Face Hub API (catches deletions, renames, gating changes).
 *  2. Trending text-generation models not yet in the registry are listed
 *     as candidates to add.
 *  3. Training-framework versions referenced by the exporters are compared
 *     against the latest releases on PyPI.
 *
 * No API keys needed. Locally: node scripts/check-registry.mjs
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const HF = 'https://huggingface.co';

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function getJson(url) {
  const res = await fetch(url, { headers: { 'User-Agent': 'dataforge-registry-check' } });
  if (!res.ok) return { status: res.status, body: null };
  return { status: res.status, body: await res.json() };
}

// --- 1. verify registry entries -------------------------------------------
const registrySource = readFileSync(join(root, 'src/engine/registry.ts'), 'utf8');
const hfIds = [...registrySource.matchAll(/hfId:\s*'([^']+)'/g)].map((m) => m[1]);

const missing = [];
const gated = [];
let verified = 0;
for (const id of hfIds) {
  const { status } = await getJson(`${HF}/api/models/${id}`);
  if (status === 200) verified++;
  else if (status === 401 || status === 403) gated.push(id);
  else missing.push({ id, status });
  await sleep(150); // stay polite with the Hub API
}

// --- 2. trending candidates -------------------------------------------------
const known = new Set(hfIds.map((id) => id.toLowerCase()));
const { body: trending } = await getJson(
  `${HF}/api/models?pipeline_tag=text-generation&sort=trendingScore&limit=50`,
);
const candidates = (trending ?? [])
  .filter((m) => !known.has(m.id.toLowerCase()))
  .filter((m) => (m.downloads ?? 0) > 5000)
  // bare org models only; skip quants/merges by common suffixes
  .filter((m) => !/(gguf|awq|gptq|bnb|4bit|8bit|exl2|nvfp4|fp8|abliterat|uncensored)/i.test(m.id))
  .slice(0, 15);

// --- 3. framework version drift ---------------------------------------------
// Versions the exporters/readme currently advertise. Update together with
// src/engine/exporters/readme.ts when bumping.
const SHIPPED = {
  axolotl: '0.17',
  trl: '1.5',
  llamafactory: '0.9.5',
  'ms-swift': '4.3',
  unsloth: '2026.6',
};
const drift = [];
for (const [pkg, shipped] of Object.entries(SHIPPED)) {
  const { body } = await getJson(`https://pypi.org/pypi/${pkg}/json`);
  const latest = body?.info?.version;
  if (latest && !latest.startsWith(shipped)) drift.push({ pkg, shipped, latest });
  await sleep(100);
}

// --- report -------------------------------------------------------------------
const lines = [];
lines.push(`## Registry freshness report`);
lines.push('');
lines.push(`Checked ${hfIds.length} registry entries against the Hugging Face Hub.`);
lines.push('');
if (missing.length === 0) {
  lines.push(`All ${verified} public entries resolve. Nothing is missing.`);
} else {
  lines.push(`### Broken entries (${missing.length})`);
  for (const m of missing) lines.push(`- \`${m.id}\` returned HTTP ${m.status}`);
}
if (gated.length > 0) {
  lines.push('');
  lines.push(`### Gated entries (expected for Llama/Gemma): ${gated.length}`);
  lines.push(gated.map((id) => `\`${id}\``).join(', '));
}
lines.push('');
lines.push(`### Trending models not in the registry`);
if (candidates.length === 0) {
  lines.push('None above the download threshold this month.');
} else {
  lines.push('| Model | Downloads | Likes |');
  lines.push('|---|---|---|');
  for (const c of candidates) {
    lines.push(
      `| [${c.id}](${HF}/${c.id}) | ${(c.downloads ?? 0).toLocaleString('en-US')} | ${c.likes ?? 0} |`,
    );
  }
  lines.push('');
  lines.push(
    'Review for fine-tune relevance. To add one: edit `src/engine/registry.ts` with the model card data (template family, context, reasoning mode, license).',
  );
}
lines.push('');
lines.push(`### Framework version drift`);
if (drift.length === 0) {
  lines.push('Exporter docs match the latest PyPI releases.');
} else {
  lines.push('| Package | Shipped docs | Latest on PyPI |');
  lines.push('|---|---|---|');
  for (const d of drift) lines.push(`| ${d.pkg} | ${d.shipped} | ${d.latest} |`);
  lines.push('');
  lines.push(
    'Update `src/engine/exporters/readme.ts` (and `SHIPPED` in `scripts/check-registry.mjs`), then verify the export formats still match upstream docs.',
  );
}
lines.push('');
lines.push('_Generated by `scripts/check-registry.mjs`._');

const report = lines.join('\n');
console.log(report);

// Non-zero exit when something needs attention, so CI can flag the run.
const needsAttention = missing.length > 0 || drift.length > 0 || candidates.length > 0;
process.exit(needsAttention ? 0 : 0);
